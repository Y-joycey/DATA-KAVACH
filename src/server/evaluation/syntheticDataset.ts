import {
  DomainType,
  EntityType,
  GroundTruthSpan,
  SyntheticDocument,
  TaskType,
} from '../types.ts';

type Segment =
  | string
  | {
      type: EntityType;
      value: string;
    };

function buildSyntheticDoc(spec: {
  id: string;
  title: string;
  category: SyntheticDocument['category'];
  domain: DomainType;
  purpose: string;
  task: TaskType;
  language: string;
  segments: Segment[];
  expected_review_or_block?: boolean;
  notes?: string;
}): SyntheticDocument {
  let text = '';
  const ground_truth: GroundTruthSpan[] = [];
  for (const seg of spec.segments) {
    if (typeof seg === 'string') {
      text += seg;
    } else {
      const start = text.length;
      text += seg.value;
      const end = text.length;
      ground_truth.push({
        entity_type: seg.type,
        start,
        end,
        value: seg.value,
      });
    }
  }
  return {
    id: spec.id,
    title: spec.title,
    category: spec.category,
    domain: spec.domain,
    purpose: spec.purpose,
    task: spec.task,
    language: spec.language,
    text,
    ground_truth,
    expected_review_or_block: spec.expected_review_or_block,
    notes: spec.notes,
  };
}

